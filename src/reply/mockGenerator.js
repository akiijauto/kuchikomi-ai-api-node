/**
 * APIキーが無い/使わない設定のときに使う生成器。常に mock=true を返す。
 *
 * Go版の Mock、PHP版の MockGenerator と同じ方針:「動かないから止まる」のではなく
 * 「経路は通るが中身はデモ」にしておくと、鍵の無いテスト環境やCIでも
 * 認証・上限・レスポンス形式まで通して確かめられる（外部通信は一切しない）。
 */
